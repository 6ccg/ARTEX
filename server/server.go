	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		writeErr(w, 400, err.Error())
		return
	}
	if req.EgressProbeURL != nil {
		value := strings.TrimSpace(*req.EgressProbeURL)
		if value != "" {
			checked, err := validateProbeURL(value)
			if err != nil {
				writeErr(w, 400, err.Error())
				return
			}
			value = checked
		}
		req.EgressProbeURL = &value
	}
	for _, proxy := range []*string{req.LLMProxy, req.WebSearchProxy, req.GlobalProxy} {
		if proxy != nil {
			if _, err := egress.ParseProxy(*proxy); err != nil {
				writeErr(w, 400, err.Error())
				return
			}
		}
	}
